export type CategoryId = typeof tournamentData.categories[number]["id"];

export function getCategoryName(categoryId: string) {
  return tournamentData.categories.find((category) => category.id === categoryId)?.name ?? categoryId;
}

export function getGroupsByCategory(categoryId: string) {
  return tournamentData.groups.filter((group) => group.categoryId === categoryId);
}

export function getTeamsByCategory(categoryId: string) {
  return tournamentData.teams.filter((team) => team.categoryId === categoryId);
}

export function getMatchesByCategory(categoryId: string) {
  return tournamentData.matches.filter((match) => match.categoryId === categoryId);
}

export function getStandingsRows(categoryId: string, groupName?: string) {
  const teams = tournamentData.teams.filter((team) =>
    team.categoryId === categoryId && (!groupName || team.group === groupName)
  );

  return teams.map((team, index) => ({
    position: index + 1,
    team: team.name,
    group: team.group,
    pj: 0,
    pg: 0,
    pe: 0,
    pp: 0,
    gf: 0,
    gc: 0,
    dg: 0,
    pts: 0,
  }));
}
